int currentNote = 0;
unsigned long noteStartTime = 0;
bool isPlaying = false;
bool shouldPlay = false;  // Boolean to control the music (true = play, false = pause)
int melodyLength = sizeof(melody) / sizeof(melody[0]);

void playBGM(int SPEAKER, bool PLAY) {
  unsigned long currentTime = millis();

  if (PLAY) {
    if (!isPlaying) {
      int duration = 1000 / durations[currentNote];
      tone(SPEAKER, melody[currentNote], duration);
      noteStartTime = currentTime;
      isPlaying = true;
    }

    if (isPlaying && currentTime - noteStartTime >= (1000 / durations[currentNote]) * 1.30) {
      noTone(SPEAKER);
      currentNote++;
      isPlaying = false;

      if (currentNote >= melodyLength) {
        currentNote = 0;  // Restart melody
      }
    }
  } else {
    noTone(SPEAKER);  // Stop the sound if music is paused
    isPlaying = false;   // Reset isPlaying to allow for proper note continuation
  }
}